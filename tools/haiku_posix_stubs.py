#!/usr/bin/env python3
"""Generate the x32 guest's side of port/linux/src/posix.h and posix_server.h.

The posix_*.c helpers run in the host (they are the platform layer's only
contact with the C library's file system, sockets and process). Their
interface is 32-bit clean, so the guest can call them directly, except for

- errno: the host's is not the guest's. Each generated wrapper calls the
  host function through an import named hostposix_<name> and copies the
  host's errno into the guest's afterwards;
- long and unsigned long (posix_server.h's), 32-bit in the guest and 64-bit
  in the host: the wrapper widens them, as the x32 ABI leaves the upper half
  of a 32-bit argument undefined.

(tools/android_posix_stubs.py does the same for the Android guest.)

Usage: haiku_posix_stubs.py output.c imports.list header...
"""

import re
import sys

WIDE = {"long": "long long", "unsigned long": "unsigned long long"}


def main():
    output, imports = sys.argv[1:3]
    headers = sys.argv[3:]
    out = [
        "/* generated by tools/haiku_posix_stubs.py from port/linux/src/posix*.h; do not edit */",
        "#include <errno.h>",
    ]
    out += [f'#include "{header.rsplit("/", 1)[-1]}"' for header in headers]
    out += ["", "int host_errno(void);", ""]
    names = []
    for header in headers:
        text = open(header, encoding="utf-8").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        prototypes = re.findall(r"^([A-Za-z_][\w \*]*?)\b(posix_\w+)\s*\(([^;]*?)\);", text, re.M | re.S)
        for ret, name, params in prototypes:
            ret = " ".join(ret.split())
            params = " ".join(params.split())
            args, host_params, call_args = [], [], []
            if params != "void":
                for param in params.split(","):
                    param = param.strip()
                    m = re.search(r"^(.*?)(\w+)\s*$", param)
                    ptype, pname = " ".join(m.group(1).split()), m.group(2)
                    args.append(pname)
                    if ptype in WIDE:
                        host_params.append(f"{WIDE[ptype]} {pname}")
                        call_args.append(f"({WIDE[ptype]}){pname}")
                    else:
                        host_params.append(param)
                        call_args.append(pname)
            host_ret = WIDE.get(ret, ret)
            host_name = "hostposix_" + name[len("posix_"):]
            names.append(host_name)
            out.append(f"{host_ret} {host_name}({', '.join(host_params) or 'void'});")
            out.append(f"{ret} {name}({params})")
            out.append("{")
            call = f"{host_name}({', '.join(call_args)})"
            if ret == "void":
                out.append(f"\t{call};")
                out.append("\terrno = host_errno();")
            else:
                out.append(f"\t{ret} host_result = ({ret}){call};")
                out.append("")
                out.append("\terrno = host_errno();")
                out.append("\treturn host_result;")
            out.append("}")
            out.append("")
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    with open(imports, "w", encoding="utf-8") as f:
        f.write("\n".join(names) + "\n")


if __name__ == "__main__":
    main()
